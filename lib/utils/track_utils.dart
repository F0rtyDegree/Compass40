import 'dart:ui';

/// Прореживает список точек трека, если его длина превышает [maxPoints].
///
/// Схема: первая половина точек разрежается (берётся каждая вторая),
/// вторая половина сохраняется полностью. Это ограничивает длину
/// трека без потери формы маршрута: старые участки теряют детализацию,
/// новые остаются плотными.
///
/// Прореживание нелинейно: при повторных циклах старые участки теряют
/// точки быстрее, чем свежие. Через несколько циклов ранние участки
/// могут быть представлены единичными точками. Это осознанный компромисс:
/// свежие данные важнее для навигации.
List<Offset> pruneTrackPoints({
  required List<Offset> points,
  int maxPoints = 5000,
}) {
  if (points.length <= maxPoints) return points;

  final half = points.length ~/ 2;
  final result = <Offset>[];

  for (int i = 0; i < half; i += 2) {
    result.add(points[i]);
  }
  for (int i = half; i < points.length; i++) {
    result.add(points[i]);
  }

  return result;
}